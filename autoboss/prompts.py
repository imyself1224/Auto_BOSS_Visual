def list_user(kb: str = "") -> str:
    """职位列表页的提示词。前面拼上求职者画像（外接知识库）。

    知识库是这个文件里唯一在**运行时**才知道的内容，所以这里是个函数而不是常量。
    agent 在启动时会先确认 kb.md 存在，所以这里基本拿不到空串；
    真拿到空串也只能退回纯读卡，那种情况下 fit 字段没有依据。
    """
    if not kb.strip():
        return LIST_BODY
    return f"""这是 BOSS 直聘的职位搜索列表页。请把当前屏幕上能看到的职位逐个读出来。

============================================================
【求职者画像 · 外接知识库】—— 判断 `fit` 的唯一依据
============================================================

{kb}

============================================================
以下是读取列表页的格式要求：

{LIST_BODY}"""


