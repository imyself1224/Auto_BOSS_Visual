def filter_row(hint: str = "") -> str:
    """读整排筛选按钮。返回每个按钮的文字和外框。

    为什么要"报整排"而不是"报一个点"：那一排里「求职类型」「职位类型」「薪资待遇」
    的中心彼此只差半个按钮宽，模型报单点时会**自信地报错**（conf 0.9+ 却稳定
    落在隔壁），而局部放大复核是围着这个错点放大的，框里根本没有正确的按钮。
    改成报整排 + 程序按文字精确匹配之后，模型只需要"读得对"，不需要"点得准"。

    `hint` 只在重试时给：把"上一次点开的是哪个下拉"告诉它，逼它重新逐字核对 ——
    否则重试就是把同一个框再报一遍，等于没重试。
    """
    if not hint:
        return _FILTER_ROW_HEAD + _FILTER_ROW_TAIL
    return (_FILTER_ROW_HEAD
            + f"\n⚠ 上一次按你报的框去点，点开的是{hint}，**不是**我们要的那个。"
              f"说明那个框没框准。这次请重新逐字核对每个按钮上的文字，"
              f"特别检查相邻按钮之间有没有框串。\n"
            + _FILTER_ROW_TAIL)


