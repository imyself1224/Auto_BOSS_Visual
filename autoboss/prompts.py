"""所有提示词模板。

视觉定位的精度几乎完全取决于坐标约定的表述是否无歧义，所以这块写得比较重。
核心手段是**网格标尺 + 归一化坐标**：

    截图前在页面里画一层网格，刻度直接标成 0–1000 的归一化值。
    模型"读到"的刻度就是要返回的数字，不需要做任何像素换算。

这样设计的原因是 DeepSeek 服务端会先把图片缩放到约 1300×1300 等效像素
（见 api-docs.deepseek.com/guides/vision），如果让模型直接报像素坐标，
一张 1600×900 的截图传上去就已经被缩放了，报回来的数字对不上真实页面。
归一化坐标和图片尺寸无关，天然免疫这个问题。
"""
